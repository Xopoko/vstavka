import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import Meta from 'gi://Meta';
import Shell from 'gi://Shell';
import St from 'gi://St';

const IMAGE_LIMIT = 10 * 1024 * 1024;
const TEXT_LIMIT = 4 * 1024 * 1024;
const TEXT = 'text/plain;charset=utf-8';
const CLIPBOARD = Meta.SelectionType.SELECTION_CLIPBOARD ?? Meta.SelectionType.CLIPBOARD;
const TYPES = ['text/uri-list', 'image/png', TEXT, 'UTF8_STRING', 'text/plain', 'STRING'];
const PRIVATE = new Set([
    'application/x-keepassxc', 'application/x-keepassxc-secret',
    'application/x-gnome-password', 'application/x-vstavka-private',
    'org.nspasteboard.concealedtype', 'org.nspasteboard.transienttype',
    'org.nspasteboard.autogeneratedtype', 'clipboard viewer ignore',
    'excludeclipboardcontentfrommonitorprocessing',
]);

export class Clipboard {
    constructor(onChange, recipient) {
        this.selection = global.display.get_selection();
        this.clipboard = St.Clipboard.get_default();
        this.theme = St.IconTheme.new();
        this.writing = false;
        this.transfer = null;
        this.signal = this.selection.connect('owner-changed', (_selection, type, owner) => {
            if (type !== CLIPBOARD)
                return;
            this.transfer?.cancel();
            // Mutter may restore a clipboard selection without the original
            // privacy formats after its client disconnects.
            const sender = recipient();
            if (owner && !(owner instanceof Meta.SelectionSourceMemory) && !this.writing && sender)
                this.capture(args => onChange(sender, args)).catch(error => console.error('Vstavka clipboard', error));
        });
    }

    dispose() {
        this.selection.disconnect(this.signal);
        this.transfer?.cancel();
    }

    async capture(onChange) {
        const offered = this.selection.get_mimetypes(CLIPBOARD) ?? [];
        if (offered.some(type => PRIVATE.has(type.toLowerCase())))
            return;
        const source = focusedApp(this.theme);
        const transfer = new Gio.Cancellable();
        this.transfer = transfer;
        let timeout = GLib.timeout_add_seconds(GLib.PRIORITY_DEFAULT, 3, () => {
            timeout = null;
            transfer.cancel();
            return GLib.SOURCE_REMOVE;
        });
        try {
            const hint = offered.find(type => type.toLowerCase() === 'x-kde-passwordmanagerhint');
            if (hint) {
                const data = await this.read(hint, 64, transfer);
                const value = data && decodeHint(data);
                if (!value || value.toLowerCase() === 'secret')
                    return;
            }

            const mime = TYPES.map(type => offered.find(value => value.toLowerCase() === type.toLowerCase()))
                .find(Boolean);
            if (!mime || transfer.is_cancelled())
                return;
            const data = await this.read(mime, mime.toLowerCase() === 'image/png' ? IMAGE_LIMIT : TEXT_LIMIT, transfer);
            if (data?.length && !transfer.is_cancelled())
                onChange([mime, data, ...source]);
        } finally {
            if (timeout !== null)
                GLib.source_remove(timeout);
            if (this.transfer === transfer)
                this.transfer = null;
        }
    }

    read(mime, limit, transfer) {
        const stream = Gio.MemoryOutputStream.new_resizable();
        return new Promise(resolve => {
            this.selection.transfer_async(CLIPBOARD, mime, limit + 1,
                stream, transfer, (selection, result) => {
                    try {
                        selection.transfer_finish(result);
                        stream.close(null);
                        if (stream.get_data_size() <= limit) {
                            resolve(stream.steal_as_bytes().get_data());
                            return;
                        }
                    } catch {
                        // A disappearing owner or cancelled transfer has no usable clipboard data.
                    }
                    resolve(null);
                });
        });
    }

    write(mime, data) {
        if (mime !== TEXT && mime !== 'image/png' && mime !== 'text/uri-list')
            return false;
        if (data.length > (mime === 'image/png' ? IMAGE_LIMIT : TEXT_LIMIT))
            return false;
        this.writing = true;
        try {
            if (mime === TEXT)
                this.clipboard.set_text(St.ClipboardType.CLIPBOARD, new TextDecoder('utf-8', {fatal: true}).decode(data));
            else
                this.clipboard.set_content(St.ClipboardType.CLIPBOARD, mime, new GLib.Bytes(data));
            return true;
        } finally {
            this.writing = false;
        }
    }
}

function focusedApp(theme) {
    const window = global.display.focus_window;
    const app = window && Shell.WindowTracker.get_default().get_window_app(window);
    if (!app)
        return ['', window?.get_wm_class() ?? '', ''];

    const icon = app.get_app_info()?.get_icon();
    const png = icon && theme.lookup_by_gicon(icon, 32, St.IconLookupFlags.NO_SVG)?.get_filename();
    return [app.get_id() ?? '', app.get_name() ?? '', png?.toLowerCase().endsWith('.png') ? png : ''];
}

function decodeHint(data) {
    try {
        return new TextDecoder('utf-8', {fatal: true}).decode(data).replace(/\0+$/, '').trim();
    } catch {
        return null;
    }
}
