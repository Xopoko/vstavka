var failures = 0;

Run("Clipboard changes honor privacy, foreground app and ownership", () =>
{
    var board = new FakePasteboard { Types = [ClipboardCapturePolicy.Text], Text = "#abc" };
    var source = new SourceApp("Synthetic source", "example.source");
    var currentProcess = false;
    var poll = new ClipboardPoll(board, () => new FrontmostSource(currentProcess, () => source));
    poll.Start();
    Check(poll.Check() is null && board.TypeReads == 0, "Startup and idle polls only check changeCount.");

    foreach (var marker in new[]
    {
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"
    })
    {
        board.Types = [ClipboardCapturePolicy.Text, marker];
        board.ChangeCount++;
        Check(poll.Check() is null && board.PayloadReads == 0, $"The {marker} marker prevents payload reads.");
    }

    board.Types = [ClipboardCapturePolicy.Text];
    var previousTypeReads = board.TypeReads;
    foreach (var access in new[] { PasteboardAccess.Default, PasteboardAccess.Ask, PasteboardAccess.AlwaysDeny })
    {
        board.Access = access;
        board.ChangeCount++;
        Check(poll.Check() is null && poll.Check() is null && board.TypeReads == previousTypeReads,
            $"Access mode {access} prevents even a type read and retries.");
    }
    board.Access = PasteboardAccess.AlwaysAllow;
    Check(poll.Check() is null && board.TypeReads == previousTypeReads, "Granting access does not replay denied changes.");

    currentProcess = true;
    board.ChangeCount++;
    Check(poll.Check() is null && board.TypeReads == previousTypeReads, "Copies detected while Vstavka is frontmost are skipped.");
    currentProcess = false;
    poll.SuppressNextChange();
    Check(poll.Check() is null, "An idle poll leaves suppression armed.");
    board.ChangeCount++;
    Check(poll.Check() is null, "External writer can use SuppressNextChange on the next change.");
    poll.RecordOwnWrite(++board.ChangeCount);
    Check(poll.Check() is null, "The writer's exact count is suppressed even when another app is frontmost.");
    poll.SuppressNextChange();
    poll.RecordOwnWrite(++board.ChangeCount);
    board.ChangeCount++;
    var capture = poll.Check();
    Check(capture?.Item.Kind == ClipKind.Color && capture.Item.SourceApp == source.Name && capture.Source == source,
        "A newer external copy is captured with the source and classified through Core.");

    board.ChangeDuringRead = true;
    board.ChangeCount++;
    Check(poll.Check() is null, "A copy superseded during the read is discarded.");
    board.ChangeDuringRead = false;
    Check(poll.Check() is not null, "The replacement count remains eligible.");

    var readsBeforeTypeChange = board.PayloadReads;
    board.ChangeDuringTypeRead = true;
    board.ChangeCount++;
    Check(poll.Check() is null && board.PayloadReads == readsBeforeTypeChange,
        "A count replaced during the privacy marker check is skipped before any payload read.");
});

Run("Representations follow priority and PNG limits", () =>
{
    var png = PngHeader(32, 32);
    var board = new FakePasteboard
    {
        Types = [ClipboardCapturePolicy.Text, ClipboardCapturePolicy.Url, ClipboardCapturePolicy.Png, ClipboardCapturePolicy.Tiff,
            ClipboardCapturePolicy.FileUrl],
        Text = "plain text", Url = "https://example.com/", Png = png, TiffAsPng = PngHeader(400, 300),
        Files = ["/file one.txt", "/file two.txt"]
    };
    Check(ClipboardCapturePolicy.Read(board, board.ChangeCount)?.Files.SequenceEqual(board.Files) == true && board.PayloadReads == 1,
        "File URL items take precedence and keep all paths.");
    board.Types = [ClipboardCapturePolicy.Text, ClipboardCapturePolicy.Url, ClipboardCapturePolicy.Png, ClipboardCapturePolicy.Tiff];
    Check(ClipboardCapturePolicy.Read(board, board.ChangeCount)?.ImageBytes == png && board.TiffConversions == 0,
        "PNG takes precedence over TIFF and text.");
    board.Png = PngHeader(5000, 5000);
    Check(ClipboardCapturePolicy.Read(board, board.ChangeCount)?.ImageBytes == board.TiffAsPng && board.TiffConversions == 1,
        "Oversized pixel dimensions fall back to a convertible TIFF.");
    board.Types = [ClipboardCapturePolicy.Text, ClipboardCapturePolicy.Url];
    var url = ClipboardCapturePolicy.Read(board, board.ChangeCount);
    Check(url?.Kind == ClipKind.Link && url.Text == board.Url, "A valid native URL wins over text.");
    board.Url = "invalid URL";
    Check(ClipboardCapturePolicy.Read(board, board.ChangeCount)?.Text == board.Text, "Invalid native URLs fall back to plain text.");
    Check(ClipboardCapturePolicy.IsSourceIconPng(png) &&
        !ClipboardCapturePolicy.IsSourceIconPng(PngHeader(33, 32)) &&
        !ClipboardCapturePolicy.IsSourceIconPng(PngHeader(32, 32, HistoryStore.MaxSourceIconBytes + 1)) &&
        !ClipboardCapturePolicy.IsClipboardPng(PngHeader(32, 32, HistoryStore.MaxImageBytes + 1)) &&
        !ClipboardCapturePolicy.IsSourceIconPng(new byte[45]), "PNG signature, pixel dimensions and byte limits are enforced.");
});

Run("Permissions refresh and route only user requests", () =>
{
    const string clipboardSettings = "x-apple.systempreferences:com.apple.settings.PrivacySecurity.extension?Privacy_Pasteboard";
    const string accessibilitySettings = "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility";
    var board = new FakePasteboard();
    var trusted = false;
    var actions = new List<string>();
    var permissions = new MacPermissions(() => board.Access, () => trusted,
        () => actions.Add("clipboard read"), () => actions.Add("accessibility prompt"), actions.Add);

    foreach (var access in new[] { PasteboardAccess.Legacy, PasteboardAccess.AlwaysAllow })
    {
        board.Access = access;
        var rows = permissions.GetPermissions();
        Check(rows[0] == new PlatformPermission("clipboard-access", PermissionRequirement.Required, PermissionState.Granted) &&
            permissions.CanReadClipboard && permissions.GetNotices().All(notice => !notice.Code.StartsWith("pasteboard-", StringComparison.Ordinal)),
            $"{access} grants clipboard access and clears clipboard notices.");
        Check(rows[1] is { Code: "accessibility", Requirement: PermissionRequirement.Optional, State: PermissionState.Missing, Request: not null },
            "Accessibility is optional and reports missing until the system trusts the process.");
    }
    Check(actions.Count == 0, "Reading rows and notices has no permission side effects.");

    foreach (var access in new[] { PasteboardAccess.Default, PasteboardAccess.Ask, PasteboardAccess.AlwaysDeny })
    {
        board.Access = access;
        var row = permissions.GetPermissions()[0];
        var notice = permissions.GetNotices()[0];
        var denied = access == PasteboardAccess.AlwaysDeny;
        Check(row is { Code: "clipboard-access", Requirement: PermissionRequirement.Required, State: PermissionState.Missing, Request: not null } &&
            !permissions.CanReadClipboard && notice.Code == (denied ? "pasteboard-access-denied" : "pasteboard-access-approval") &&
            notice.Resolve == row.Request, $"{access} requires clipboard access and exposes the same request in its notice.");
        row.Request!();
        Check(actions.Count == 1 && actions[0] == (denied ? clipboardSettings : "clipboard read"), $"{access} routes one action.");
        actions.Clear();
    }
    var request = permissions.GetPermissions()[1].Request!;
    request();
    permissions.GetNotices().Single(notice => notice.Code == "accessibility-permission").Resolve!();
    Check(actions.SequenceEqual(["accessibility prompt", accessibilitySettings]),
        "The first Accessibility request prompts and the next one opens Accessibility settings.");
    trusted = true;
    request();
    Check(permissions.GetPermissions()[1] == new PlatformPermission("accessibility", PermissionRequirement.Optional, PermissionState.Granted) &&
        permissions.GetNotices().All(notice => notice.Code != "accessibility-permission") && actions.Count == 2,
        "Granting trust clears the notice and makes a stale request harmless.");
});

Run("Start at login reflects system status and errors", () =>
{
    nint service = 0;
    var status = MacLoginItemStatus.NotRegistered;
    var accepted = true;
    var attempts = new List<bool>();
    var startup = new MacStartupRegistration(() => service,
        type => type == 42 ? status : throw new InvalidOperationException("No service class."),
        (type, enabled) =>
        {
            Check(type == 42, "Mutations require a service class.");
            attempts.Add(enabled);
            if (accepted)
                status = enabled ? MacLoginItemStatus.RequiresApproval : MacLoginItemStatus.NotRegistered;
            return accepted;
        });

    Check(!startup.IsSupported && startup.Status is null && !startup.IsEnabled && !startup.TrySetEnabled(true) && attempts.Count == 0,
        "An unavailable service supports neither status nor mutations.");
    service = 42;
    Check(startup.IsSupported && !startup.IsEnabled && startup.TrySetEnabled(true) &&
        startup.Status == MacLoginItemStatus.RequiresApproval && !startup.IsEnabled,
        "Successful registration can require approval before it is enabled.");
    status = MacLoginItemStatus.Enabled;
    accepted = false;
    Check(startup.IsEnabled && !startup.TrySetEnabled(false) && startup.IsEnabled, "Unregister failure leaves the service enabled.");
    accepted = true;
    status = MacLoginItemStatus.RequiresApproval;
    Check(startup.TrySetEnabled(false) && startup.Status == MacLoginItemStatus.NotRegistered && !startup.IsEnabled &&
        attempts.SequenceEqual([true, false, false]), "A service pending approval can still be unregistered.");
    accepted = false;
    status = MacLoginItemStatus.NotFound;
    Check(!startup.TrySetEnabled(true) && !startup.IsEnabled, "A register error is returned to the caller.");
});

Run("Hotkey mapping, failed replacement and synchronization context", () =>
{
    Check(MacGlobalHotkey.DefaultGesture == "Shift+Meta+V" &&
        MacGlobalHotkey.SupportedGestures.SequenceEqual(["Shift+Meta+V", "Ctrl+Meta+V", "Alt+Meta+V"]),
        "The default and suggestions use the shared gesture syntax.");
    (string Gesture, uint Key, uint Modifiers)[] examples =
    [
        ("Shift+Meta+V", 0x09, 0x0300), ("Ctrl+Meta+V", 0x09, 0x1100), ("Option+Cmd+V", 0x09, 0x0900),
        ("Ctrl+Shift+A", 0x00, 0x1200), ("Alt+Z", 0x06, 0x0800), ("Meta+0", 0x1D, 0x0100),
        ("Ctrl+9", 0x19, 0x1000), ("Ctrl+Alt+Shift+Meta+F1", 0x7A, 0x1B00), ("Alt+F20", 0x5A, 0x0800),
        ("Ctrl+Space", 0x31, 0x1000),
    ];
    var calls = 0;
    using (var hotkey = new MacGlobalHotkey((key, modifiers, callback) =>
    {
        var expected = examples[calls++];
        Check((key, modifiers) == (expected.Key, expected.Modifiers), $"Carbon mapping for {expected.Gesture}.");
        return new FakeRegistration(callback);
    }))
    {
        foreach (var (gesture, _, _) in examples)
            Check(hotkey.TryRegister(gesture), $"{gesture} reaches native registration.");
        foreach (var gesture in new[] { "V", "Shift+V", "Ctrl+Escape", "Ctrl+F21", "Meta+F22", "Alt+F23", "Ctrl+F24" })
            Check(!hotkey.TryRegister(gesture), $"{gesture} is unusable or unsupported.");
        Check(calls == examples.Length, "Unsupported gestures never reach native registration.");
    }

    var registrations = new List<FakeRegistration>();
    var context = new QueuedContext();
    var previousContext = SynchronizationContext.Current;
    SynchronizationContext.SetSynchronizationContext(context);
    try
    {
        using var hotkey = new MacGlobalHotkey((_, modifiers, callback) =>
        {
            if (modifiers == 0x1100)
                return null;
            var registration = new FakeRegistration(callback);
            registrations.Add(registration);
            return registration;
        });
        var pressed = 0;
        hotkey.Pressed += () => pressed++;
        Check(hotkey.TryRegister(MacGlobalHotkey.DefaultGesture) && hotkey.TryRegister(" cmd+shift+v ") &&
            !hotkey.TryRegister("Ctrl+Cmd+V") && registrations.Count == 1 && !registrations[0].Disposed,
            "An unavailable replacement keeps the current native registration.");
        registrations[0].Callback();
        Check(pressed == 0, "The native callback posts to the captured context.");
        context.Drain();
        Check(pressed == 1, "The context reports the press.");
        registrations[0].Callback();
        Check(hotkey.TryRegister("Option+Cmd+V") && registrations[0].Disposed, "A successful replacement releases the previous registration.");
        registrations[1].Callback();
        context.Drain();
        Check(pressed == 2, "Late callbacks from the previous registration are skipped.");
    }
    finally
    {
        SynchronizationContext.SetSynchronizationContext(previousContext);
    }
});

return failures == 0 ? 0 : 1;

void Run(string name, Action test)
{
    try
    {
        test();
        Console.WriteLine($"PASS {name}");
    }
    catch (Exception error)
    {
        failures++;
        Console.Error.WriteLine($"FAIL {name}: {error}");
    }
}

static void Check(bool condition, string message)
{
    if (!condition)
        throw new InvalidOperationException(message);
}

static byte[] PngHeader(uint width, uint height, int byteCount = 45)
{
    var bytes = new byte[byteCount];
    ReadOnlySpan<byte> header = [137, 80, 78, 71, 13, 10, 26, 10, 0, 0, 0, 13, 73, 72, 68, 82];
    header.CopyTo(bytes);
    BinaryPrimitives.WriteUInt32BigEndian(bytes.AsSpan(16), width);
    BinaryPrimitives.WriteUInt32BigEndian(bytes.AsSpan(20), height);
    return bytes;
}

sealed class FakePasteboard : IPasteboard
{
    public long ChangeCount { get; set; }
    public PasteboardAccess Access { get; set; } = PasteboardAccess.Legacy;
    public string[] Types { get; set; } = [];
    public bool ChangeDuringRead { get; set; }
    public bool ChangeDuringTypeRead { get; set; }
    public int TypeReads { get; private set; }
    public int PayloadReads { get; private set; }
    public int TiffConversions { get; private set; }
    public string Text { get; set; } = "";
    public string Url { get; set; } = "";
    public string[] Files { get; set; } = [];
    public byte[]? Png { get; set; }
    public byte[]? TiffAsPng { get; set; }

    public IReadOnlyList<string> ReadTypeNames()
    {
        TypeReads++;
        if (ChangeDuringTypeRead)
            ChangeCount++;
        return Types;
    }
    public string[] ReadFilePaths() { PayloadReads++; return Files; }
    public byte[]? ReadPng() { PayloadReads++; return Png; }
    public byte[]? ConvertTiffToPng() { PayloadReads++; TiffConversions++; return TiffAsPng; }

    public string ReadString(string type)
    {
        PayloadReads++;
        if (ChangeDuringRead)
            ChangeCount++;
        return type == ClipboardCapturePolicy.Url ? Url : Text;
    }
}

sealed class FakeRegistration(Action callback) : IDisposable
{
    public Action Callback { get; } = callback;
    public bool Disposed { get; private set; }
    public void Dispose() => Disposed = true;
}

sealed class QueuedContext : SynchronizationContext
{
    private readonly Queue<(SendOrPostCallback Callback, object? State)> callbacks = new();
    public override void Post(SendOrPostCallback callback, object? state) => callbacks.Enqueue((callback, state));

    public void Drain()
    {
        while (callbacks.TryDequeue(out var item))
            item.Callback(item.State);
    }
}
