using System.Buffers.Binary;
using Vstavka.Core;

namespace Vstavka.Platform.MacOS;

internal enum PasteboardAccess : long { Legacy = -1, Default = 0, Ask = 1, AlwaysAllow = 2, AlwaysDeny = 3 }

internal interface IPasteboard
{
    long ChangeCount { get; }
    PasteboardAccess Access { get; }
    IReadOnlyList<string> ReadTypeNames();
    string[] ReadFilePaths();
    byte[]? ReadPng();
    byte[]? ConvertTiffToPng();
    string? ReadString(string type);
}

internal static class ClipboardCapturePolicy
{
    internal const string Text = "public.utf8-plain-text";
    internal const string Url = "public.url";
    internal const string FileUrl = "public.file-url";
    internal const string Png = "public.png";
    internal const string Tiff = "public.tiff";
    internal const int MaxImagePixels = 16_000_000;

    private static readonly HashSet<string> IgnoredTypes = new(StringComparer.OrdinalIgnoreCase)
    {
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type"
    };

    internal static bool CanReadInBackground(PasteboardAccess access) =>
        access is PasteboardAccess.Legacy or PasteboardAccess.AlwaysAllow;

    internal static ClipItem? Read(IPasteboard board, long changeCount)
    {
        var types = new HashSet<string>(board.ReadTypeNames(), StringComparer.OrdinalIgnoreCase);
        if (types.Overlaps(IgnoredTypes) || board.ChangeCount != changeCount)
            return null;

        if (types.Contains(FileUrl))
        {
            var files = board.ReadFilePaths();
            return files.Length is > 0 and <= HistoryStore.MaxFilesPerItem
                ? new ClipItem { Kind = ClipKind.Files, Files = files }
                : null;
        }

        if (types.Contains(Png) || types.Contains(Tiff))
        {
            var png = types.Contains(Png) ? board.ReadPng() : null;
            if (!IsClipboardPng(png) && types.Contains(Tiff) && board.ChangeCount == changeCount)
                png = board.ConvertTiffToPng();
            return IsClipboardPng(png) ? new ClipItem { Kind = ClipKind.Image, ImageBytes = png } : null;
        }

        if (types.Contains(Url) && board.ReadString(Url) is { } url &&
            Uri.TryCreate(url.Trim(), UriKind.Absolute, out var parsed) && !parsed.IsFile)
            return new ClipItem { Kind = ClipKind.Link, Text = url };

        var text = types.Contains(Text) && board.ChangeCount == changeCount ? board.ReadString(Text) : null;
        return !string.IsNullOrWhiteSpace(text) && text.Length <= HistoryStore.MaxTextLength
            ? new ClipItem { Kind = ClipItem.DetectTextKind(text), Text = text }
            : null;
    }

    internal static bool IsClipboardPng(byte[]? png) =>
        png is { Length: <= HistoryStore.MaxImageBytes } &&
        TryGetPngSize(png, out var width, out var height) && (ulong)width * height <= MaxImagePixels;

    internal static bool IsSourceIconPng(byte[]? png) =>
        png is { Length: <= HistoryStore.MaxSourceIconBytes } &&
        TryGetPngSize(png, out var width, out var height) && width <= 32 && height <= 32 && png[28] == 0;

    internal static bool TryGetPngSize(ReadOnlySpan<byte> png, out uint width, out uint height)
    {
        width = height = 0;
        ReadOnlySpan<byte> signature = [137, 80, 78, 71, 13, 10, 26, 10, 0, 0, 0, 13];
        if (png.Length < 45 || !png.StartsWith(signature) || !png[12..16].SequenceEqual("IHDR"u8))
            return false;
        width = BinaryPrimitives.ReadUInt32BigEndian(png[16..]);
        height = BinaryPrimitives.ReadUInt32BigEndian(png[20..]);
        return width > 0 && height > 0;
    }
}
