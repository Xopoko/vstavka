using System.Text;
using Vstavka.Core;

namespace Vstavka.Platform.Linux;

internal static class LinuxClipboard
{
    public const string Text = "text/plain;charset=utf-8";
    public const string Files = "text/uri-list";
    public const string Image = "image/png";
    public const string PasswordHint = "x-kde-passwordManagerHint";
    public const int TextBytes = HistoryStore.MaxTextLength * 4;
    public const int HintBytes = 64;

    public static IReadOnlyList<string> PayloadTypes { get; } =
        [Files, Image, Text, "UTF8_STRING", "text/plain", "STRING"];

    private static readonly HashSet<string> PrivateTypes = new(StringComparer.OrdinalIgnoreCase)
    {
        "application/x-keepassxc", "application/x-keepassxc-secret",
        "application/x-gnome-password", "application/x-vstavka-private",
        "org.nspasteboard.concealedtype", "org.nspasteboard.transienttype",
        "org.nspasteboard.autogeneratedtype", "clipboard viewer ignore",
        "excludeclipboardcontentfrommonitorprocessing"
    };

    private static readonly UTF8Encoding Utf8 = new(encoderShouldEmitUTF8Identifier: false, throwOnInvalidBytes: true);

    public static bool HasPrivateMarker(IEnumerable<string> formats) => formats.Any(PrivateTypes.Contains);

    public static bool IsPrivateHint(ReadOnlySpan<byte> data)
    {
        try
        {
            var hint = Utf8.GetString(data).TrimEnd('\0').Trim();
            return hint.Length == 0 || hint.Equals("secret", StringComparison.OrdinalIgnoreCase);
        }
        catch (DecoderFallbackException)
        {
            return true;
        }
    }

    public static ClipboardCapture? Read(LinuxClipboardData payload, Func<string, byte[]?> loadIcon)
    {
        if (payload.Data.Length == 0)
            return null;

        var item = new ClipItem();
        if (string.Equals(payload.Mime, Image, StringComparison.OrdinalIgnoreCase))
        {
            if (payload.Data.Length > HistoryStore.MaxImageBytes || !ClipboardImageLimits.FitsPngDimensions(payload.Data))
                return null;
            item.Kind = ClipKind.Image;
            item.ImageBytes = payload.Data;
        }
        else
        {
            if (payload.Data.Length > TextBytes || !PayloadTypes.Contains(payload.Mime, StringComparer.OrdinalIgnoreCase))
                return null;
            string content;
            try
            {
                var encoding = string.Equals(payload.Mime, "STRING", StringComparison.OrdinalIgnoreCase)
                    ? Encoding.Latin1 : Utf8;
                content = encoding.GetString(payload.Data).TrimEnd('\0');
            }
            catch (DecoderFallbackException)
            {
                return null;
            }
            if (string.Equals(payload.Mime, Files, StringComparison.OrdinalIgnoreCase))
            {
                item.Kind = ClipKind.Files;
                item.Files = ReadFiles(content);
                if (item.Files.Length is 0 or > HistoryStore.MaxFilesPerItem)
                    return null;
            }
            else
            {
                if (string.IsNullOrWhiteSpace(content) || content.Length > HistoryStore.MaxTextLength)
                    return null;
                item.Kind = ClipItem.DetectTextKind(content);
                item.Text = content;
            }
        }

        item.SourceApp = !string.IsNullOrWhiteSpace(payload.Name) ? payload.Name : payload.DesktopId ?? "";
        var source = item.SourceApp.Length == 0 ? null : new SourceApp(item.SourceApp,
            string.IsNullOrEmpty(payload.DesktopId) ? null : payload.DesktopId,
            Icon(payload.IconPath, loadIcon));
        return new ClipboardCapture(item, source);
    }

    public static (string Mime, byte[] Data) Write(ClipItem item, bool plainText)
    {
        if (!plainText && item.Kind == ClipKind.Image && item.ImageBytes is { Length: > 0 } image)
            return (Image, image);
        var text = item.Kind == ClipKind.Files ? string.Join('\n', item.Files) : item.Text;
        return (Text, Encoding.UTF8.GetBytes(text));
    }

    private static string[] ReadFiles(string content)
    {
        var paths = new List<string>();
        foreach (var raw in content.Split('\n'))
        {
            var line = raw.Trim();
            if (line.StartsWith('#') || !Uri.TryCreate(line, UriKind.Absolute, out var uri) || !uri.IsFile ||
                (uri.Host.Length > 0 && !uri.Host.Equals("localhost", StringComparison.OrdinalIgnoreCase)))
                continue;
            // AbsolutePath keeps POSIX separators on Windows, including in fake tests.
            var path = Uri.UnescapeDataString(uri.AbsolutePath);
            if (!path.StartsWith('/') || path.Contains('\0'))
                continue;
            paths.Add(path);
            if (paths.Count > HistoryStore.MaxFilesPerItem)
                break;
        }
        return paths.ToArray();
    }

    private static byte[]? Icon(string? path, Func<string, byte[]?> loadIcon)
    {
        if (path?.EndsWith(".png", StringComparison.OrdinalIgnoreCase) != true)
            return null;
        var png = loadIcon(path);
        return png is { Length: <= HistoryStore.MaxSourceIconBytes } &&
            ClipboardImageLimits.TryReadPngSize(png, out var width, out var height) && width <= 32 && height <= 32
            ? png : null;
    }

    public static byte[]? LoadIcon(string path)
    {
        if (!Path.IsPathFullyQualified(path))
            return null;
        try
        {
            var length = new FileInfo(path).Length;
            if (length is < 45 or > HistoryStore.MaxSourceIconBytes)
                return null;
            using var stream = File.OpenRead(path);
            var bytes = new byte[(int)length];
            stream.ReadExactly(bytes);
            return stream.ReadByte() == -1 ? bytes : null;
        }
        catch (Exception error) when (error is IOException or UnauthorizedAccessException or ArgumentException)
        {
            return null;
        }
    }
}
